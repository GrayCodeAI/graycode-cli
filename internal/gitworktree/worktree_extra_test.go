func TestCreate_NotAGitRepo(t *testing.T) {
	tmpDir := t.TempDir()
	_, _, err := Create(context.Background(), tmpDir, "test-branch")
	if err == nil {
		t.Fatal("expected error for non-git directory")
	}
	if !strings.Contains(err.Error(), "not a git repository") {
		t.Errorf("error = %q, want to contain 'not a git repository'", err.Error())
	}
}

func TestCreate_WithGitRepo(t *testing.T) {
	// Create a temp git repo
	tmpDir := t.TempDir()

	// Initialize a git repo
	runGit(t, tmpDir, "init")
	runGit(t, tmpDir, "config", "user.email", "test@test.com")
	runGit(t, tmpDir, "config", "user.name", "Test")
	// Create initial commit
	if err := os.WriteFile(filepath.Join(tmpDir, "README.md"), []byte("# Test"), 0644); err != nil {
		t.Fatal(err)
	}
	runGit(t, tmpDir, "add", ".")
	runGit(t, tmpDir, "commit", "-m", "initial")

	// Create worktree
	path, cleanup, err := Create(context.Background(), tmpDir, "test-worktree")
	if err != nil {
		t.Fatalf("Create error: %v", err)
	}
	defer cleanup()

	if path == "" {
		t.Error("expected non-empty path")
	}
	if _, err := os.Stat(path); os.IsNotExist(err) {
		t.Error("worktree path should exist")
	}
}

