func TestCreate_Cleanup(t *testing.T) {
	tmpDir := t.TempDir()
	runGit(t, tmpDir, "init")
	runGit(t, tmpDir, "config", "user.email", "test@test.com")
	runGit(t, tmpDir, "config", "user.name", "Test")
	if err := os.WriteFile(filepath.Join(tmpDir, "README.md"), []byte("# Test"), 0644); err != nil {
		t.Fatal(err)
	}
	runGit(t, tmpDir, "add", ".")
	runGit(t, tmpDir, "commit", "-m", "initial")

	path, cleanup, err := Create(context.Background(), tmpDir, "cleanup-test")
	if err != nil {
		t.Fatalf("Create error: %v", err)
	}

	// Verify path exists
	if _, err := os.Stat(path); os.IsNotExist(err) {
		t.Fatal("worktree path should exist before cleanup")
	}

	// Run cleanup
	cleanup()

	// Verify path is removed
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Error("worktree path should be removed after cleanup")
	}
}

func TestCreate_CleanupWithTimeout(t *testing.T) {
	tmpDir := t.TempDir()
	runGit(t, tmpDir, "init")
	runGit(t, tmpDir, "config", "user.email", "test@test.com")
	runGit(t, tmpDir, "config", "user.name", "Test")
	if err := os.WriteFile(filepath.Join(tmpDir, "README.md"), []byte("# Test"), 0644); err != nil {
		t.Fatal(err)
	}
	runGit(t, tmpDir, "add", ".")
	runGit(t, tmpDir, "commit", "-m", "initial")

	_, cleanup, err := Create(context.Background(), tmpDir, "timeout-test")
	if err != nil {
		t.Fatalf("Create error: %v", err)
	}

	// Cleanup should complete within reasonable time
	done := make(chan struct{})
	go func() {
		cleanup()
		close(done)
	}()

	select {
	case <-done:
		// Good
	case <-time.After(35 * time.Second):
		t.Error("cleanup took too long (should timeout at 30s)")
	}
}

// --- Helper functions ---

func runGit(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.CommandContext(context.Background(), "git", args...)
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %s failed: %v\n%s", strings.Join(args, " "), err, string(out))
	}
}
